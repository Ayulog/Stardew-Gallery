# Requires PowerShell 7. Builds assets/pinyin.txt, the table behind pinyin search, from the Unicode Han Database.
# Download Unihan.zip from https://www.unicode.org/Public/UCD/latest/ucd/, extract Unihan_Readings.txt and pass its
# path as -Readings. Run with -Check to compare with the current table without writing.
#
# Covers CJK Unified Ideographs (U+4E00-U+9FFF). Readings come from kMandarin, kTGHZ2013 and kXHC1983, which follow
# modern usage, so a polyphone keeps each of its common readings but not the archaic ones. Tones are dropped and ü is
# written v, as on pinyin keyboards. Characters stay in code point order and syllables are sorted, so the same input
# always gives the same file. The Unicode license is copied into the header from licenses/Unicode-License-v3.txt,
# which also ships in the release package.
[CmdletBinding()]
param(
    [Parameter(Mandatory)] [string] $Readings,
    [switch] $Check
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$targetPath = Join-Path $root 'assets/pinyin.txt'
$licensePath = Join-Path $root 'licenses/Unicode-License-v3.txt'
$characters = [Collections.Generic.SortedDictionary[string, Text.StringBuilder]]::new([StringComparer]::Ordinal)
# "code syllable" pairs, so a reading listed by several fields is added once.
$seen = [Collections.Generic.HashSet[string]]::new()
$version = $null

switch -Regex -CaseSensitive -File (Resolve-Path -LiteralPath $Readings).Path {
    '^# Unicode Version (\S+)' { $version = $Matches[1]; continue }
    '^U\+([0-9A-F]{4})\t(?:kMandarin|kTGHZ2013|kXHC1983)\t(.+)$' {
        $hex = $Matches[1]
        $values = $Matches[2]
        $code = [Convert]::ToInt32($hex, 16)
        if ($code -lt 0x4E00 -or $code -gt 0x9FFF) { continue }
        # Dictionary fields put a location before each reading ("0001.010:ā"); kMandarin lists readings alone.
        foreach ($token in $values.Split(' ')) {
            $reading = $token.Substring($token.LastIndexOf(':') + 1)
            # Decomposed, ü is u and a combining diaeresis; the tone marks are the other combining marks.
            $syllable = ($reading.Normalize([Text.NormalizationForm]::FormD) -creplace 'u\u0308', 'v' -creplace '\p{Mn}', '').ToLowerInvariant()
            if ($syllable -cnotmatch '^[a-z]+$') { throw "Unexpected reading '$reading' for U+$hex." }
            if (-not $seen.Add("$code $syllable")) { continue }
            if (-not $characters.ContainsKey($syllable)) { $characters[$syllable] = [Text.StringBuilder]::new() }
            [void] $characters[$syllable].Append([char] $code)
        }
    }
}
if ($null -eq $version) { throw 'The readings file has no "# Unicode Version" line; pass Unihan_Readings.txt.' }
if ($characters.Count -eq 0) { throw 'No readings were found; pass Unihan_Readings.txt.' }

$lines = @(
    '# Toneless pinyin for CJK Unified Ideographs (U+4E00-U+9FFF). Each line is a syllable, a space, and its characters.'
    "# Generated by tools/Generate-PinyinTable.ps1 from the Unicode Han Database (Unihan_Readings.txt, Unicode $version):"
    '# kMandarin, kTGHZ2013 and kXHC1983. Tones are dropped and ü is written v.'
    '#'
)
$lines += Get-Content -LiteralPath $licensePath -Encoding utf8 | ForEach-Object { ('# ' + $_).TrimEnd() }
$lines += $characters.GetEnumerator() | ForEach-Object { "$($_.Key) $($_.Value)" }
$text = ($lines -join "`n") + "`n"

$characterCount = ($characters.Values | Measure-Object -Property Length -Sum).Sum
$summary = "$($characters.Count) syllables, $characterCount readings, Unicode $version"
if ($Check) {
    $current = (Test-Path -LiteralPath $targetPath) ? [IO.File]::ReadAllText($targetPath).Replace("`r`n", "`n") : $null
    if ($current -ceq $text) { "Up to date: assets/pinyin.txt ($summary)" }
    else { "Would update: assets/pinyin.txt ($summary)"; exit 1 }
    return
}
[IO.File]::WriteAllText($targetPath, $text, [Text.UTF8Encoding]::new($false))
"Wrote assets/pinyin.txt ($summary, $([Text.Encoding]::UTF8.GetByteCount($text)) bytes)"
